/** Sorteia uma frase que nao saiu nas ultimas mensagens. */
export function sortearFrase(lista, recentes = []) {
  const usadas = new Set(recentes);
  const livres = lista.filter((f) => !usadas.has(f));
  const opcoes = livres.length > 0 ? livres : lista;
  return opcoes[Math.floor(Math.random() * opcoes.length)];
}
